// Core Artifact Lifecycle Schema
// Defines the authoritative 17-state lifecycle for all Burstpoint media artifacts.
// Enforces valid transitions and rejects invalid state jumps.

const LIFECYCLE_STATES = Object.freeze({
  GENERATED: 'GENERATED',
  SIMULATED: 'SIMULATED',
  SCORED: 'SCORED',
  RENDERED: 'RENDERED',
  VALIDATED: 'VALIDATED',
  APPROVED: 'APPROVED',
  SCHEDULED: 'SCHEDULED',
  UPLOAD_PENDING: 'UPLOAD_PENDING',
  UPLOAD_IN_PROGRESS: 'UPLOAD_IN_PROGRESS',
  UPLOAD_PREFLIGHT_PASSED: 'UPLOAD_PREFLIGHT_PASSED',
  UPLOADED: 'UPLOADED',
  PROCESSING: 'PROCESSING',
  PUBLISHED: 'PUBLISHED',
  ANALYTICS_AVAILABLE: 'ANALYTICS_AVAILABLE',
  FAILED: 'FAILED',
  RETRY_PENDING: 'RETRY_PENDING',
  REJECTED: 'REJECTED'
});

const ALLOWED_TRANSITIONS = {
  [LIFECYCLE_STATES.GENERATED]: [LIFECYCLE_STATES.SIMULATED, LIFECYCLE_STATES.FAILED],
  [LIFECYCLE_STATES.SIMULATED]: [LIFECYCLE_STATES.SCORED, LIFECYCLE_STATES.FAILED],
  [LIFECYCLE_STATES.SCORED]: [LIFECYCLE_STATES.RENDERED, LIFECYCLE_STATES.REJECTED, LIFECYCLE_STATES.FAILED],
  [LIFECYCLE_STATES.RENDERED]: [LIFECYCLE_STATES.VALIDATED, LIFECYCLE_STATES.FAILED],
  [LIFECYCLE_STATES.VALIDATED]: [LIFECYCLE_STATES.APPROVED, LIFECYCLE_STATES.REJECTED, LIFECYCLE_STATES.FAILED],
  [LIFECYCLE_STATES.APPROVED]: [LIFECYCLE_STATES.SCHEDULED, LIFECYCLE_STATES.FAILED],
  [LIFECYCLE_STATES.SCHEDULED]: [LIFECYCLE_STATES.UPLOAD_PENDING, LIFECYCLE_STATES.UPLOAD_PREFLIGHT_PASSED, LIFECYCLE_STATES.FAILED],
  [LIFECYCLE_STATES.UPLOAD_PENDING]: [LIFECYCLE_STATES.UPLOAD_PREFLIGHT_PASSED, LIFECYCLE_STATES.UPLOAD_IN_PROGRESS, LIFECYCLE_STATES.FAILED],
  [LIFECYCLE_STATES.UPLOAD_PREFLIGHT_PASSED]: [LIFECYCLE_STATES.UPLOAD_IN_PROGRESS, LIFECYCLE_STATES.FAILED],
  [LIFECYCLE_STATES.UPLOAD_IN_PROGRESS]: [LIFECYCLE_STATES.UPLOADED, LIFECYCLE_STATES.RETRY_PENDING, LIFECYCLE_STATES.FAILED],
  [LIFECYCLE_STATES.UPLOADED]: [LIFECYCLE_STATES.PROCESSING, LIFECYCLE_STATES.PUBLISHED, LIFECYCLE_STATES.FAILED],
  [LIFECYCLE_STATES.PROCESSING]: [LIFECYCLE_STATES.PUBLISHED, LIFECYCLE_STATES.FAILED],
  [LIFECYCLE_STATES.PUBLISHED]: [LIFECYCLE_STATES.ANALYTICS_AVAILABLE, LIFECYCLE_STATES.FAILED],
  [LIFECYCLE_STATES.ANALYTICS_AVAILABLE]: [],
  [LIFECYCLE_STATES.FAILED]: [LIFECYCLE_STATES.RETRY_PENDING],
  [LIFECYCLE_STATES.RETRY_PENDING]: [LIFECYCLE_STATES.UPLOAD_PENDING, LIFECYCLE_STATES.SIMULATED, LIFECYCLE_STATES.FAILED],
  [LIFECYCLE_STATES.REJECTED]: []
};

class LifecycleManager {
  static isValidState(state) {
    return Object.values(LIFECYCLE_STATES).includes(state);
  }

  static canTransition(fromState, toState) {
    if (!this.isValidState(fromState) || !this.isValidState(toState)) return false;
    const allowed = ALLOWED_TRANSITIONS[fromState] || [];
    return allowed.includes(toState);
  }

  static transition(entity, toState, metadata = {}) {
    const currentState = entity.lifecycleState || LIFECYCLE_STATES.GENERATED;
    if (!this.canTransition(currentState, toState)) {
      throw new Error(`Invalid lifecycle transition: Cannot move from "${currentState}" to "${toState}".`);
    }

    entity.lifecycleState = toState;
    entity.updatedAt = new Date().toISOString();
    if (!entity.stateHistory) entity.stateHistory = [];
    entity.stateHistory.push({
      from: currentState,
      to: toState,
      timestamp: entity.updatedAt,
      metadata
    });

    return entity;
  }
}

module.exports = {
  LIFECYCLE_STATES,
  ALLOWED_TRANSITIONS,
  LifecycleManager
};
